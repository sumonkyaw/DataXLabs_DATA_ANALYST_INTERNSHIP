# 1. Feature Selection & Encoding
y = df['no_show']

features = [
    'age',
    'gender',
    'distance_to_clinic_km',
    'clinic_id',
    'clinic_type',
    'appointment_type',
    'consultation_fee_gbp',
    'appointment_hour',
    'days_in_advance',
    'is_weekend',
    'is_peak_hour',
    'patient_total_appointments',
    'patient_previous_noshow_count',
    'patient_noshow_rate',
    'days_since_last_visit',
    'has_chronic_condition_flag',
    'sms_reminder_sent',
    'reminder_hours_before',
    'reminder_response',
    'number_of_reminders_sent'
]

X = df[features]
y = df['no_show']

# 2. Train-Test Split (80/20 Stratified)
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42,  stratify=y)

# Identify Categorical and Numerical Columns
categorical_features = [
    'gender',
    'clinic_id',
    'clinic_type',
    'appointment_type',
    'reminder_response'
]

numerical_features = [
    'age',
    'distance_to_clinic_km',
    'consultation_fee_gbp',
    'appointment_hour',
    'days_in_advance',
    'is_weekend',
    'is_peak_hour',
    'patient_total_appointments',
    'patient_previous_noshow_count',
    'patient_noshow_rate',
    'days_since_last_visit',
    'has_chronic_condition_flag',
    'sms_reminder_sent',
    'reminder_hours_before',
    'number_of_reminders_sent'
]

# Encode Categorical Variables
preprocessor = ColumnTransformer(
    transformers=[
        ('categorical',OneHotEncoder(handle_unknown='ignore'),
         categorical_features),
        ('numerical','passthrough',numerical_features)
                ]
    )

# 3. Model Building (Decision Tree with depth constraint to prevent overfitting)

model = DecisionTreeClassifier( max_depth=5,min_samples_split=20,
                               min_samples_leaf=10,random_state=42, class_weight='balanced')

pipeline = Pipeline(steps=[('preprocessor', preprocessor),('classifier', model)])

pipeline.fit(X_train, y_train)

y_pred = pipeline.predict(X_test)

y_prob = pipeline.predict_proba(X_test)[:, 1]

# 4. Model Evaluation

print("=== Classification Report ===")
print(classification_report(y_test, y_pred))
print("Accuracy:", accuracy_score(y_test, y_pred))
print(f"ROC-AUC Score: {roc_auc_score(y_test, y_prob):.4f}")

# Confusion Matrix

cm = confusion_matrix(y_test, y_pred)

sns.heatmap(cm,annot=True,fmt='d',cmap='Blues')
plt.title('Confusion Matrix')
plt.xlabel('Predicted')
plt.ylabel('Actual')
plt.show()

RocCurveDisplay.from_predictions(y_test,y_prob)

plt.title('ROC Curve - No-Show Prediction')
plt.show()

# 5. Feature Importance Extraction

tree_model = pipeline.named_steps['classifier']
