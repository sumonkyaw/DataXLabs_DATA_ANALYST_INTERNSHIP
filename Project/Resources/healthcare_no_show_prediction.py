# Create Risk Categories & three risk levels:

def risk_category(probability):
    if probability >= 0.70:
        return 'High Risk'
    elif probability >= 0.40:
        return 'Medium Risk'
    else:
        return 'Low Risk'

df['risk_category'] = df['no_show_probability'].apply(risk_category)
